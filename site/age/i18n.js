  /** Le texte d'une clé dans une langue, avec ses {variables}. Une clé absente en anglais retombe sur le français. */
  function traduire(langue, cle, vars) {
    const brut = (T[langue] && T[langue][cle]) ?? T.fr[cle] ?? cle;
    return brut.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? String(vars[k]) : m));
  }

